// Embed the remote script into the app bundle so the app alone can install it.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const source = path.resolve(here, "..", "..", "remote-script", "HellboyProd");
const files = {};
for (const name of fs.readdirSync(source).sort()) {
  if (name.endsWith(".py")) files[name] = fs.readFileSync(path.join(source, name), "utf8");
}
if (!files["__init__.py"]) throw new Error(`no remote script found in ${source}`);
const version = /SCRIPT_VERSION = "([^"]+)"/.exec(files["__init__.py"])?.[1] ?? "unknown";
const out = path.resolve(here, "..", "src", "generated", "remote-script.ts");
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(
  out,
  "// Generated by app/scripts/embed.mjs - do not edit.\n" +
    `export const SCRIPT_VERSION = ${JSON.stringify(version)};\n` +
    `export const REMOTE_SCRIPT: Record<string, string> = ${JSON.stringify(files, null, 1)};\n`,
);
console.log(`embedded ${Object.keys(files).length} remote script files (v${version})`);
